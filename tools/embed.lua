-- Embed slc's own parts into one C file: the compiler and macro sources,
-- the bundled vocabularies and the runtime sources. `make dist` links this with
-- the launcher next to the host's LuaJIT; nothing else is copied into the tree.
--
--   luajit tools/embed.lua [-o out.c]

local root = arg[0]:match('^(.*)/tools/[^/]*$') or '.'
local out_path = root .. '/build/dist/embedded.c'
for i = 1, #arg do
    if arg[i] == '-o' then i = i + 1; out_path = arg[i] end
end

local files = { 'slc.lua', 'macro.lua' }
local function list(pattern)
    local p = io.popen('ls ' .. root .. '/' .. pattern .. ' 2>/dev/null')
    for line in p:lines() do files[#files + 1] = (line:gsub('^%./', '')) end
    p:close()
end
list('macro/*.lua')
list('slc/*.lua')
list('lib/*.slc')
list('runtime/*.h')
list('runtime/*.slc')
list('runtime/*.c')
list('tests/fuzz/*.lua')
list('tests/fuzz/regressions/*.lua')
-- built by `make dist`: linked into the binary and carried for `slc build`
files[#files + 1] = 'build/dist/libslc_rt.a'
list('build/dist/header_tables.lua')

local function read(path)
    local f = assert(io.open(root .. '/' .. path, 'rb'))
    local s = f:read '*a'
    f:close()
    return s
end

-- Lua sources ship as LuaJIT bytecode: no source parsing at startup
local function bytecode(name, text)
    if os.getenv('SLC_EMBED_DEBUG') then io.stderr:write('bytecode ', name, '\n') end
    local chunk, err = loadstring(text, '@' .. name)
    assert(chunk, name .. ': ' .. tostring(err))
    return string.dump(chunk)
end

-- FNV-1a over every name and byte: the cache directory's identity
local function fnv(s, h)
    h = h or 2166136261
    for i = 1, #s do
        h = bit.bxor(h, s:byte(i))
        h = bit.band(h * 16777619, 0xffffffff)
    end
    return h
end

-- a C string literal: printable ASCII stays, everything else is octal, so no
-- escape can run into the next character
local function literal(s)
    local out = { '"' }
    for i = 1, #s do
        local b = s:byte(i)
        if b == 34 then out[#out + 1] = '\\"'
        elseif b == 92 then out[#out + 1] = '\\\\'
        elseif b >= 32 and b <= 126 then out[#out + 1] = string.char(b)
        else out[#out + 1] = ('\\%03o'):format(b) end
    end
    out[#out + 1] = '"'
    return table.concat(out)
end

local RENAME = { ['build/dist/libslc_rt.a'] = 'runtime/libslc_rt.a',
                 ['build/dist/header_tables.lua'] = 'runtime/header_tables.lua' }

local parts = { '/* Generated by tools/embed.lua: slc\'s own parts. Do not edit. */',
    '#include <stddef.h>',
    'typedef struct slc_embedded_file { const char *name; const char *data; size_t size; } slc_embedded_file;',
    'const slc_embedded_file slc_embedded_files[] = {' }
local hash = 2166136261
local total = 0
for _, path in ipairs(files) do
    local name = RENAME[path] or path
    local text = read(path)
    local compiler_source = name == 'slc.lua' or name == 'macro.lua'
        or name:match('^slc/') or name:match('^macro/')
    if compiler_source and name:match('%.lua$') then
        text = bytecode(name, text)
    end
    hash = fnv(name, fnv(text, hash))
    total = total + #text
    parts[#parts + 1] = ('{ "%s",'):format(name)
    parts[#parts + 1] = literal(text)
    parts[#parts + 1] = (', %d },'):format(#text)
end
parts[#parts + 1] = '};'
parts[#parts + 1] = 'const size_t slc_embedded_count = sizeof(slc_embedded_files) / sizeof(slc_embedded_files[0]);'
parts[#parts + 1] = ('const char *slc_embedded_hash = "%s";'):format(bit.tohex(hash))

os.execute('mkdir -p ' .. root .. '/build/dist')
local out = assert(io.open(out_path, 'w'))
out:write(table.concat(parts, '\n'), '\n')
out:close()
print(('embedded %d files, %d bytes, hash %s -> %s'):format(#files, total, bit.tohex(hash), out_path))
