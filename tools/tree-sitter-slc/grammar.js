// SLC editor grammar. GPL-3.0-or-later; see ../../COPYING.
const sep = (rule, delimiter = ',') => seq(rule, repeat(seq(delimiter, rule)));
module.exports = grammar({
  name: 'slc',
  extras: $ => [/\s/, $.comment, $._endall_reset],
  externals: $ => [$.long_string, $.long_comment, $.name_argument, $._endall, $._implicit_end, $._error_sentinel, $._endall_reset],
  word: $ => $.identifier,
  conflicts: $ => [[$.expression_statement, $._expression], [$.parameter, $._expression], [$.field, $._expression], [$.parameter, $.vararg_expression], [$.handler, $._expression]],
  rules: {
    source_file: $ => repeat($._statement),
    comment: $ => choice(token(seq('--', /[^\r\n]*/)), $.long_comment),
    identifier: _ => /[a-zA-Z_][a-zA-Z_0-9]*/,
    number: _ => /(?:0[xX][0-9a-fA-F]+(?:\.[0-9a-fA-F]*)?(?:[pP][+-]?[0-9]+)?|[0-9]+(?:\.[0-9]+)?(?:[eE][+-]?[0-9]+)?|\.[0-9]+(?:[eE][+-]?[0-9]+)?)(?:[uU]?[lL][lL])?/,
    string: $ => choice(seq('"', repeat(choice($.escape_sequence, token.immediate(/[^"\\\r\n]+/))), '"'), seq("'", repeat(choice($.escape_sequence, token.immediate(/[^'\\\r\n]+/))), "'"), $.long_string),
    escape_sequence: _ => token.immediate(/\\(?:\r?\n|[^\r\n])/),
    boolean: _ => choice('true', 'false'),
    nil: _ => 'nil',
    _statement: $ => choice(';', $.local_declaration, $.assignment_statement, $.expression_statement, $.return_statement, $.break_statement, $.if_statement, $.while_statement, $.repeat_statement, $.for_statement, $.function_declaration, $.export_statement, $.goto_statement, $.label_statement),
    block: $ => repeat1($._statement),
    local_declaration: $ => seq('local', sep($.binding), optional(seq('=', sep($._expression)))),
    binding: $ => prec.right(seq(field('name', $.identifier), optional(choice($.type_annotation, '...')))),
    type_annotation: $ => seq(':', field('type', $._type)),
    _type: $ => choice($.identifier, $.type_call, $.type_member, $.type_application),
    type_application: $ => prec.left(16, seq($._type, alias($.name_argument, $.identifier))),
    type_call: $ => prec.left(15, seq($._type, '(', optional(sep($._expression)), ')')),
    type_member: $ => prec.left(15, seq($._type, '.', $.identifier)),
    assignment_statement: $ => seq(sep($._expression), '=', sep($._expression)),
    expression_statement: $ => choice($.call_expression, $.lambda),
    return_statement: $ => prec.right(seq('return', optional(sep($._expression)))),
    break_statement: _ => choice('break', 'continue'),
    export_statement: $ => seq('export', sep($._expression)),
    goto_statement: $ => seq('goto', $.identifier),
    label_statement: $ => seq('::', $.identifier, '::'),
    if_statement: $ => seq('if', $._expression, 'then', optional($.block), repeat(seq('elseif', $._expression, 'then', optional($.block))), optional(seq('else', optional($.block))), 'end'),
    while_statement: $ => seq('while', $._header_expression, 'do', optional($.block), 'end'),
    repeat_statement: $ => seq('repeat', optional($.block), 'until', $._expression),
    for_statement: $ => seq('for', sep($.binding), choice(seq('=', sep($._header_expression)), seq('in', sep($._header_expression))), 'do', optional($.block), 'end'),
    function_declaration: $ => seq(optional('local'), 'function', field('name', $.function_name), $.parameters, optional($.type_annotation), optional($.block), 'end'),
    function_name: $ => seq($.identifier, repeat(seq('.', $.identifier)), optional(seq(':', $.identifier))),
    parameters: $ => prec(20, seq('(', optional(sep($.parameter)), ')')),
    parameter: $ => choice(seq($.identifier, optional(choice($.type_annotation, '...'))), seq('...', optional(choice($.identifier, $.type_annotation)))),
    lambda: $ => prec.right(seq('do', optional($.parameters), choice(
      seq($.type_annotation, choice(seq('=', $._expression), seq(optional($.block), choice('end', alias($._endall, 'endall'))))),
      seq('=', $._expression),
      seq(optional($.block), choice('end', alias($._endall, 'endall'), $._implicit_end))
    ))),
    function_expression: $ => seq('function', $.parameters, optional($.block), 'end'),
    struct_expression: $ => seq('struct', $.table_constructor),
    table_constructor: $ => seq('{', optional(seq(sep($.field, choice(',', ';')), optional(choice(',', ';')))), '}'),
    // `.name` is the shorthand for `name = name`.
    field: $ => choice($.handler, seq('.', $.identifier), seq($.identifier, choice('=', ':'), $._expression),
      seq('[', $._expression, ']', '=', $._expression), $._expression),
    // A keyed handler is a lambda without the leading `do`.
    handler: $ => seq(field('name', $.identifier), $.parameters, optional($.type_annotation), choice(seq('=', $._expression), seq(optional($.block), 'end'))),
    _expression: $ => choice($.identifier, $.number, $.string, $.boolean, $.nil, $.vararg_expression, $.parenthesized_expression, $.table_constructor, $.struct_expression, $.lambda, $.function_expression, $.binary_expression, $.unary_expression, $.call_expression, $.member_expression, $.index_expression, $.spread_expression),
    // A loop's `do` is a delimiter, not a trailing lambda argument. Parentheses
    // and argument lists still admit ordinary expressions, including lambdas.
    _header_expression: $ => choice($.identifier, $.number, $.string, $.boolean, $.nil, $.parenthesized_expression, $.table_constructor, $.header_binary, $.header_unary, $.header_call, $.header_member, $.header_index),
    header_member: $ => prec.left(15, seq($._header_expression, '.', field('member', $.identifier))),
    header_index: $ => prec.left(15, seq($._header_expression, '[', $._expression, ']')),
    header_call: $ => prec.left(14, seq(field('function', $._header_expression), optional(seq(':', field('method', $.identifier))), $.header_arguments)),
    header_arguments: $ => choice(seq('(', optional(sep($._expression)), ')'), $.table_constructor, $.string, $.number, $.boolean, alias($.name_argument, $.identifier)),
    header_unary: $ => prec(11, seq(choice('not', '-', '#'), $._header_expression)),
    header_binary: $ => choice(...[['or', 1], ['and', 2], [choice('<', '>', '<=', '>=', '~=', '=='), 3], ['..', 5, true], [choice('+', '-'), 6], [choice('*', '/', '%'), 7], ['^', 12, true]].map(([op, p, right]) => (right ? prec.right : prec.left)(p, seq($._header_expression, op, $._header_expression)))),
    vararg_expression: $ => prec.right(seq('...', optional($.identifier))),
    parenthesized_expression: $ => seq('(', $._expression, ')'),
    member_expression: $ => prec.left(15, seq($._expression, '.', field('member', $.identifier))),
    index_expression: $ => prec.left(15, seq($._expression, '[', $._expression, ']')),
    spread_expression: $ => prec.left(15, seq($._expression, '...')),
    call_expression: $ => prec.left(14, seq(field('function', $._expression), optional(seq(':', field('method', $.identifier))), field('arguments', $.arguments))),
    arguments: $ => choice(seq('(', optional(sep($._expression)), ')'), $.table_constructor, $.string, $.number, $.boolean, $.lambda, alias($.name_argument, $.identifier)),
    unary_expression: $ => prec(11, seq(field('operator', choice('not', '-', '#')), $._expression)),
    binary_expression: $ => choice(...[
      ['or', 1], ['and', 2], [choice('<', '>', '<=', '>=', '~=', '=='), 3], ['..', 5, true],
      [choice('+', '-'), 6], [choice('*', '/', '%'), 7], ['^', 12, true],
    ].map(([op, priority, right]) => (right ? prec.right : prec.left)(priority, seq(field('left', $._expression), field('operator', op), field('right', $._expression)))))
  }
});
