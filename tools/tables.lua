-- Aggregate the probe answers a recording run saw into one embedded table.
--
--   SLC_PROBE_RECORD=file luajit slc.lua --gccjit -o /dev/null prog.slc
--   luajit tools/tables.lua [-o build/dist/header_tables.lua] file...
--
-- The result is a Lua chunk keyed like the probe cache, carrying the C-library
-- identity it was recorded against: a run that sees another library probes.
local root = arg[0]:match('^(.*)/tools/[^/]*$') or '.'
package.path = root .. '/?.lua;' .. package.path

local out_path = root .. '/build/dist/header_tables.lua'
local inputs = {}
for i = 1, #arg do
    if arg[i] == '-o' then i = i + 1; out_path = arg[i]
    elseif arg[i]:sub(1, 1) ~= '-' then inputs[#inputs + 1] = arg[i]
    end
end

local seen, out = {}, {}
local total = 0
for _, path in ipairs(inputs) do
    local f = io.open(path, 'rb')
    if f then
        local data = f:read '*a'
        f:close()
        -- key \0 result chunk \0 key \0 ...
        local at = 1
        while true do
            local key, after_key = data:match('([^%z]+)%z()', at)
            if not key then break end
            local _, text, after = data:match('()(.-)%z()', after_key)
            if not text then break end
            at = after
            if not seen[key] then
                seen[key] = true
                out[#out + 1] = ('[%q] = [==[\n%s]==],'):format(key, text)
                total = total + 1
            end
        end
    end
end

local identity = require('slc.probe').libc_identity()
local f = assert(io.open(out_path, 'w'))
f:write('-- Generated by tools/tables.lua: probe answers for the bundled libraries.\n')
f:write(('return { _identity = %q,\n'):format(identity))
f:write(table.concat(out, '\n'))
f:write('\n}\n')
f:close()
print(('%d probe answers (%s) -> %s'):format(total, identity, out_path))
